USE ROLE ACCOUNTADMIN;

-- ----------------------------------------------------------------------------
-- 1. PROVISION DATABASE, SCHEMAS & CORE TABLES
-- ----------------------------------------------------------------------------
CREATE DATABASE IF NOT EXISTS ANALYTICS_PROD
    COMMENT = 'Production analytical warehouse for DataPulse Reverse ETL';

CREATE SCHEMA IF NOT EXISTS ANALYTICS_PROD.MARTS
    WITH MANAGED ACCESS
    COMMENT = 'Curated analytical gold marts exposed to Reverse ETL';

CREATE SCHEMA IF NOT EXISTS ANALYTICS_PROD.AUDIT
    WITH MANAGED ACCESS
    COMMENT = 'Operational state, high-watermarks, and Dead Letter Queue (DLQ)';

CREATE TABLE IF NOT EXISTS ANALYTICS_PROD.MARTS.FCT_CUSTOMER_PROFITABILITY (
    CUSTOMER_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    EMAIL VARCHAR(255) NOT NULL,
    REGION VARCHAR(32) NOT NULL,
    LIFETIME_VALUE_USD NUMBER(12, 2) NOT NULL,
    CHURN_RISK_SCORE FLOAT NOT NULL,
    ACCOUNT_TIER VARCHAR(32) NOT NULL,
    UPDATED_AT TIMESTAMP_NTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS ANALYTICS_PROD.AUDIT.DATA_PULSE_WATERMARKS (
    SYNC_ID VARCHAR(128) NOT NULL PRIMARY KEY,
    LAST_WATERMARK_VALUE TIMESTAMP_NTZ NOT NULL,
    ROWS_SYNCED INTEGER NOT NULL,
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS ANALYTICS_PROD.AUDIT.DATA_PULSE_DLQ (
    DLQ_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    SYNC_ID VARCHAR(128) NOT NULL,
    CUSTOMER_ID VARCHAR(64) NOT NULL,
    ERROR_CODE VARCHAR(64) NOT NULL,
    ERROR_DETAIL VARCHAR(1024) NOT NULL,
    PAYLOAD_JSON VARCHAR(16384) NOT NULL,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- ----------------------------------------------------------------------------
-- 2. PROVISION SERVICE ROLE & RSA 2048-BIT KEY-PAIR SERVICE USER
-- ----------------------------------------------------------------------------
USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS ROLE_DATA_PULSE_SERVICE
    COMMENT = 'Least-privilege service role for DataPulse Reverse ETL engine';

CREATE USER IF NOT EXISTS SVC_DATA_PULSE
    LOGIN_NAME = 'SVC_DATA_PULSE'
    DISPLAY_NAME = 'DataPulse Reverse ETL Service Account'
    DEFAULT_WAREHOUSE = 'WH_DATA_PULSE_XS'
    DEFAULT_ROLE = 'ROLE_DATA_PULSE_SERVICE'
    DEFAULT_NAMESPACE = 'ANALYTICS_PROD.MARTS'
    MUST_CHANGE_PASSWORD = FALSE
    RSA_PUBLIC_KEY = 'MIIBIjANBgkqhkiG9w0BAQEFAAOCAQ8AMIIBCgKCAQEA_REPLACE_WITH_REAL_PUBLIC_KEY_IDAQAB'
    COMMENT = 'Passwordless service user authenticated via 2048-bit RSA Key-Pair';

GRANT ROLE ROLE_DATA_PULSE_SERVICE TO USER SVC_DATA_PULSE;
GRANT ROLE ROLE_DATA_PULSE_SERVICE TO ROLE SYSADMIN;

-- ----------------------------------------------------------------------------
-- 3. PRINCIPLE OF LEAST PRIVILEGE (PoLP) GRANTS
-- Read-only on MARTS.FCT_CUSTOMER_PROFITABILITY; Write allowed only on AUDIT.
-- ----------------------------------------------------------------------------
GRANT USAGE ON DATABASE ANALYTICS_PROD TO ROLE ROLE_DATA_PULSE_SERVICE;
GRANT USAGE ON SCHEMA ANALYTICS_PROD.MARTS TO ROLE ROLE_DATA_PULSE_SERVICE;
GRANT USAGE ON SCHEMA ANALYTICS_PROD.AUDIT TO ROLE ROLE_DATA_PULSE_SERVICE;

GRANT SELECT ON TABLE ANALYTICS_PROD.MARTS.FCT_CUSTOMER_PROFITABILITY
    TO ROLE ROLE_DATA_PULSE_SERVICE;

GRANT SELECT, INSERT, UPDATE ON TABLE ANALYTICS_PROD.AUDIT.DATA_PULSE_WATERMARKS
    TO ROLE ROLE_DATA_PULSE_SERVICE;

GRANT SELECT, INSERT, UPDATE ON TABLE ANALYTICS_PROD.AUDIT.DATA_PULSE_DLQ
    TO ROLE ROLE_DATA_PULSE_SERVICE;

-- ----------------------------------------------------------------------------
-- 4. DYNAMIC DATA MASKING (COLUMN-LEVEL SECURITY) & ROW ACCESS POLICY (RLS)
-- ----------------------------------------------------------------------------
USE ROLE ACCOUNTADMIN;

CREATE OR REPLACE MASKING POLICY ANALYTICS_PROD.MARTS.pii_email_mask
    AS (val STRING) RETURNS STRING ->
    CASE
        WHEN CURRENT_ROLE() IN ('ACCOUNTADMIN', 'ROLE_DATA_PULSE_SERVICE') THEN val
        ELSE REGEXP_REPLACE(val, '^[^@]+', 'REDACTED_PII')
    END;

ALTER TABLE ANALYTICS_PROD.MARTS.FCT_CUSTOMER_PROFITABILITY
    MODIFY COLUMN EMAIL SET MASKING POLICY ANALYTICS_PROD.MARTS.pii_email_mask;

CREATE OR REPLACE ROW ACCESS POLICY ANALYTICS_PROD.MARTS.region_isolation_policy
    AS (region_col VARCHAR) RETURNS BOOLEAN ->
    CASE
        WHEN CURRENT_ROLE() IN ('ACCOUNTADMIN', 'ROLE_DATA_PULSE_SERVICE') THEN TRUE
        WHEN CURRENT_ROLE() = 'ROLE_ANALYST_EU' AND region_col = 'EU' THEN TRUE
        ELSE FALSE
    END;

ALTER TABLE ANALYTICS_PROD.MARTS.FCT_CUSTOMER_PROFITABILITY
    ADD ROW ACCESS POLICY ANALYTICS_PROD.MARTS.region_isolation_policy ON (REGION);

